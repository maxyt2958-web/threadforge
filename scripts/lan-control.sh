#!/usr/bin/env bash
# Start/stop/status for the LAN + HTTPS dev deployment on this machine.
# The Wi-Fi IP is DHCP and DOES change — every config file, the TLS certificate and the
# firewall rules are regenerated from the current address on each `start`.
# Usage: ./scripts/lan-control.sh {start|stop|status}
set -euo pipefail
cd "$(dirname "$0")/.."

IFACE="${LAN_IFACE:-wlan0}"

detect() {
  IP=$(ip -4 -o addr show dev "$IFACE" | awk '{print $4}' | cut -d/ -f1 | head -1)
  SUBNET=$(ip -4 route | awk -v i="$IFACE" '$0 ~ "dev "i && $0 ~ /proto kernel/ && $0 ~ /scope link/ {print $1; exit}')
  [[ -n "$IP" && -n "$SUBNET" ]] || { echo "no IPv4 on $IFACE" >&2; exit 1; }
}

configure() {
  detect
  echo "LAN IP: $IP  (subnet $SUBNET)"

  local secret
  secret=$(grep '^TFORGE_TURN_SECRET=' .env 2>/dev/null | cut -d= -f2- || true)
  [[ -n "$secret" && "$secret" != REPLACE* ]] || secret=$(openssl rand -hex 32)

  printf 'KC_HOSTNAME=http://%s:8081\nTFORGE_TURN_RELAY_IP=%s\nTFORGE_TURN_SECRET=%s\n' \
    "$IP" "$IP" "$secret" > .env

  cat > compose.override.yml <<EOF
services:
  keycloak:
    ports:
      - "127.0.0.1:8081:8080"
      - "${IP}:8081:8080"
  # coturn: real secret, LAN bind, no --allow-loopback-peers escape hatch.
  # --no-dtls is not accepted by the coturn:4.18 image, so it is omitted.
  coturn:
    command:
      - "-n"
      - "--log-file=stdout"
      - "--listening-port=3478"
      - "--listening-ip=${IP}"
      - "--relay-ip=${IP}"
      - "--external-ip=${IP}"
      - "--min-port=49160"
      - "--max-port=49200"
      - "--realm=threadforge.local"
      - "--fingerprint"
      - "--use-auth-secret"
      - "--static-auth-secret=\${TFORGE_TURN_SECRET}"
      - "--no-tls"
      - "--no-cli"
      - "--no-multicast-peers"
      - "--denied-peer-ip=169.254.0.0-169.254.255.255"
EOF

  printf '%s\n' \
    '# LAN dev profile — regenerated by scripts/lan-control.sh. Gitignored.' \
    'server.address=0.0.0.0' \
    'server.forward-headers-strategy=native' \
    'server.tomcat.remoteip.internal-proxies=127\\.0\\.0\\.1|::1' \
    "spring.security.oauth2.client.provider.keycloak.issuer-uri=http://${IP}:8081/realms/tforge-realm" \
    "spring.security.oauth2.resourceserver.jwt.issuer-uri=http://${IP}:8081/realms/tforge-realm" \
    "tforge.allowed-origins=https://${IP}:8443,http://${IP}:8080,http://localhost:8080,http://127.0.0.1:8080" \
    "tforge.p2p.bind-address=${IP}" \
    'tforge.dev-tools.enabled=true' \
    'tforge.assets.unbundled=true' \
    > src/main/resources/application-dev.properties

  mkdir -p data/tls
  if ! openssl x509 -in data/tls/cert.pem -noout -ext subjectAltName 2>/dev/null | grep -q "IP Address:${IP}"; then
    echo "regenerating TLS cert for $IP"
    openssl req -x509 -newkey rsa:2048 -nodes -days 365 \
      -keyout data/tls/key.pem -out data/tls/cert.pem \
      -subj "/CN=${IP}" \
      -addext "subjectAltName=IP:${IP},DNS:localhost,IP:127.0.0.1" >/dev/null 2>&1
  fi

  # UFW is active with a default-deny input policy on this host. Rules are scoped to the
  # current LAN subnet, never "Anywhere".
  if command -v ufw >/dev/null 2>&1; then
    for rule in \
      "to any port 8080 proto tcp" "to any port 8443 proto tcp" \
      "to any port 8081 proto tcp" "to any port 8082:8120 proto tcp" \
      "to any port 50000 proto udp" \
      "to any port 3478 proto udp" \
      "to any port 3478 proto tcp" "to any port 49160:49200 proto udp"; do
      sudo -n ufw allow from "$SUBNET" $rule >/dev/null 2>&1 || \
        echo "warning: could not open UFW rule: $rule (run with sudo once)" >&2
    done
    # Fandem UDP peer discovery uses IPv6 link-local multicast [ff02::1]:50000.
    sudo -n ufw allow from fe80::/10 to any port 50000 proto udp >/dev/null 2>&1 || \
      echo "warning: could not open IPv6 UFW rule for Fandem discovery (50000/udp)" >&2
  fi
}

start() {
  configure
  newgrp docker -c 'cd "$PWD" && docker compose up -d' >/dev/null
  # Keycloak start-dev keeps the realm in memory: re-apply the origin whitelist after recreate.
  for i in $(seq 1 40); do
    newgrp docker -c 'cd "$PWD" && docker compose logs keycloak 2>&1' \
      | grep -q "Realm 'tforge-realm' imported" && break
    sleep 2
  done
  newgrp docker -c "cd \"$PWD\" && ./scripts/dev-lan-realm-docker.sh $IP" >/dev/null

  # Always restart the JVM and proxy: issuer URIs, allowed origins and the cert may have changed.
  [[ -f data/app.pid ]] && kill "$(cat data/app.pid)" 2>/dev/null || true
  [[ -f data/tls/proxy.pid ]] && kill "$(cat data/tls/proxy.pid)" 2>/dev/null || true
  sleep 2

  # The packaged jar contains the application-dev.properties from BUILD time, so external config
  # files alone are not enough after a DHCP change. Spring relaxed-binding env vars override the
  # literal values baked into the jar's application-dev.properties.
  export KEYCLOAK_CLIENT_SECRET=$(jq -r '.clients[] | select(.clientId=="tforge-client") | .secret' keycloak/realm.json)
  export KEYCLOAK_ISSUER_URI="http://${IP}:8081/realms/tforge-realm"
  export SPRING_SECURITY_OAUTH2_CLIENT_PROVIDER_KEYCLOAK_ISSUER_URI="http://${IP}:8081/realms/tforge-realm"
  export SPRING_SECURITY_OAUTH2_RESOURCESERVER_JWT_ISSUER_URI="http://${IP}:8081/realms/tforge-realm"
  export SERVER_ADDRESS="0.0.0.0"
  export SERVER_FORWARD_HEADERS_STRATEGY=native
  export SERVER_TOMCAT_REMOTEIP_INTERNAL_PROXIES='127\.0\.0\.1|::1'
  export TFORGE_ALLOWED_ORIGINS="https://${IP}:8443,http://${IP}:8080,http://localhost:8080,http://127.0.0.1:8080"
  export TFORGE_P2P_BIND_ADDRESS="${IP}"
  export TFORGE_ASSETS_UNBUNDLED=true
  export TFORGE_DEV_TOOLS_ENABLED=true
  export TFORGE_TURN_URLS="turn:${IP}:3478?transport=udp"
  export TFORGE_TURN_SECRET=$(grep '^TFORGE_TURN_SECRET=' .env | cut -d= -f2-)
  nohup mise exec java@25 -- java -Xms256m -Xmx768m -jar build/libs/threadforge-1.0.0.jar \
    --spring.profiles.active=dev > data/app.log 2>&1 &
  echo $! > data/app.pid
  LAN_IP="$IP" nohup node scripts/lan-https-proxy.mjs > data/tls/proxy.log 2>&1 &
  echo $! > data/tls/proxy.pid

  echo "Starting. Use THIS link: https://${IP}:8443"
  echo "Health: https://${IP}:8443/actuator/health"
}
stop() {
  [[ -f data/app.pid ]] && kill "$(cat data/app.pid)" 2>/dev/null || true
  [[ -f data/tls/proxy.pid ]] && kill "$(cat data/tls/proxy.pid)" 2>/dev/null || true
  rm -f data/app.pid data/tls/proxy.pid
  newgrp docker -c 'cd "$PWD" && docker compose down' >/dev/null
  echo "Stopped. Chat history (Postgres volume) and data/ are preserved."
}
status() {
  detect
  echo "Current LAN IP: $IP"
  echo "Correct link:   https://${IP}:8443"
  newgrp docker -c 'cd "$PWD" && docker compose ps'
  for name in app proxy; do
    f="data/${name}.pid"; [[ "$name" == proxy ]] && f="data/tls/proxy.pid"
    if [[ -f "$f" ]] && kill -0 "$(cat "$f")" 2>/dev/null; then echo "$name: running (pid $(cat "$f"))"; else echo "$name: stopped"; fi
  done
}
case "${1:-status}" in
  start) start ;;
  stop) stop ;;
  status) status ;;
  *) echo "usage: $0 {start|stop|status}" >&2; exit 2 ;;
esac
